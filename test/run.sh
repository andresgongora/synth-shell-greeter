#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'

##==================================================================================================
##	DEPENDENCY CHECKS
##==================================================================================================

requireCommand() { command -v "$1" >/dev/null 2>&1 || { printf "Abort: '%s' not found\n" "$1" >&2; exit 1; }; }

requireCommand bash

##==================================================================================================
##	GLOBALS
##==================================================================================================

declare -r SCRIPT_NAME="${0##*/}"
declare SCRIPT_DIR
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
declare -r SCRIPT_DIR
declare -a TEST_FILES=("$SCRIPT_DIR"/*_test.sh)

##==================================================================================================
##	CORE FUNCTIONS
##==================================================================================================

runTestFiles() {
    local test_file

    if [[ ! -e "${TEST_FILES[0]}" ]]; then
        printf '%s: no tests found in %s\n' "$SCRIPT_NAME" "$SCRIPT_DIR" >&2
        exit 1
    fi

    for test_file in "${TEST_FILES[@]}"; do
        printf 'RUN: %s\n' "${test_file##*/}"
        bash "$test_file"
    done
}

##==================================================================================================
##	ARGUMENT PARSING
##==================================================================================================

[[ $# -eq 0 ]] || { printf '%s: no arguments expected\n' "$SCRIPT_NAME" >&2; exit 1; }

##==================================================================================================
##	MAIN
##==================================================================================================

main() {
    runTestFiles
    printf 'PASS: %s test file(s)\n' "${#TEST_FILES[@]}"
}

##==================================================================================================
##	SCRIPT ENTRY POINT
##==================================================================================================

main
