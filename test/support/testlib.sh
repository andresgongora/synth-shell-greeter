#!/usr/bin/env bash
set -Eeuo pipefail
IFS=$'\n\t'

##==================================================================================================
##	DEPENDENCY CHECKS
##==================================================================================================

requireCommand() { command -v "$1" >/dev/null 2>&1 || { printf "Abort: '%s' not found\n" "$1" >&2; exit 1; }; }

requireCommand mkdir
requireCommand mktemp

##==================================================================================================
##	GLOBALS
##==================================================================================================

declare PROJECT_ROOT
PROJECT_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd -P)"
declare -r PROJECT_ROOT
declare -r BUILD_ROOT="$PROJECT_ROOT/test/build"

##==================================================================================================
##	UTILITIES
##==================================================================================================

die() {
    printf 'FAIL: %s\n' "$1" >&2
    exit 1
}

##==================================================================================================
##	CORE FUNCTIONS
##==================================================================================================

assertFile() {
    local file_path="$1"

    [[ -f "$file_path" ]] || die "missing file: $file_path"
}

createTestRoot() {
    mkdir -p "$BUILD_ROOT"
    mktemp -d "$BUILD_ROOT/${1}.XXXXXX"
}
